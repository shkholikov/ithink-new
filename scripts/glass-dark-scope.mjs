// Generates components/glassyui/styles/dark-scope.css.
// GlassyUI keys its light theme off an ancestor [data-lg-theme='light'] and keeps dark values on
// :root and the base classes. A dark section inside a light page therefore inherits light tokens.
// This file re-declares the dark values under [data-lg-theme='dark'], later in the same layer, so a
// dark section wins over the light page root. Re-run after updating liquid.css.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const dir = path.join(__dirname, "../components/glassyui/styles");
const root = postcss.parse(fs.readFileSync(path.join(dir, "liquid.css"), "utf8"));
const LIGHT = "[data-lg-theme='light']";

const topLevel = (r) => r.parent.type === "atrule" && r.parent.name === "layer" && r.parent.parent.type === "root";
const base = new Map();
root.walkRules((r) => {
	if (!topLevel(r) || r.selector.includes("data-lg-theme")) return;
	for (const sel of r.selector.split(",").map((s) => s.trim())) {
		const m = base.get(sel) ?? new Map();
		r.walkDecls((d) => d.parent === r && m.set(d.prop, d.value));
		base.set(sel, m);
	}
});

const out = [];
const missing = [];
root.walkRules((r) => {
	if (!topLevel(r)) return;
	const sel = r.selector.trim();
	if (!sel.startsWith(LIGHT) || /data-lg-(mode|reduce|scene)|lg-scene/.test(sel)) return;
	const rest = sel.slice(LIGHT.length).trim();
	const baseSel = rest || ":root";
	const values = base.get(baseSel) ?? new Map();
	const decls = [];
	r.walkDecls((d) => {
		if (d.parent !== r) return;
		if (values.has(d.prop)) decls.push(`    ${d.prop}: ${values.get(d.prop)};`);
		else if (!rest && ["padding", "color-scheme", "--lg-ink", "--lg-highlight-strength"].includes(d.prop)) return;
		else missing.push(`${sel} ${d.prop}`);
	});
	// Values the dark theme leaves unset: the registered initial value, or the :root fallback.
	if (!rest) decls.push("    color-scheme: dark;", "    --lg-ink: var(--lg-ink-dark);", "    --lg-highlight-strength: 0;");
	if (decls.length) out.push(`  [data-lg-theme='dark']${rest ? " " + rest : ""} {\n${decls.join("\n")}\n  }`);
});

fs.writeFileSync(
	path.join(dir, "dark-scope.css"),
	`/* Generated by scripts/glass-dark-scope.mjs. Do not edit. */\n@layer components {\n${out.join("\n\n")}\n}\n`
);
console.log(`wrote ${out.length} rules`);
if (missing.length) console.log("no dark base value for:\n  " + missing.join("\n  "));
